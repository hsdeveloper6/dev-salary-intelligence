def select_and_rename(v1, year):
    """Step 2: keep COLUMNS[year] in order, renamed. Fails loudly if a source column is missing."""
    pairs = COLUMNS[year]
    missing = [src for src, _ in pairs if src not in v1.columns]
    if missing:
        raise KeyError(f"[{year}] v1 is missing columns: {missing}")
    return v1[[src for src, _ in pairs]].set_axis([dst for _, dst in pairs], axis=1)


def build(year, root=ROOT):
    raw = pd.read_csv(root / f"data/{year}/results.csv", low_memory=False)
    v1_path = root / f"data/clean/survey_{year}_cleaned.csv"
    clean_survey(raw, year).to_csv(v1_path, index=False)

    v2 = select_and_rename(pd.read_csv(v1_path, low_memory=False), year)
    out = root / f"data/cleaned_v2/survey_{year}_v2.csv"
    v2.to_csv(out, index=False)
    print(f"saved {out.relative_to(root)}: {v2.shape[0]:,} rows, {v2.shape[1]} columns\n")


def main():
    (ROOT / "data/clean").mkdir(parents=True, exist_ok=True)
    (ROOT / "data/cleaned_v2").mkdir(parents=True, exist_ok=True)
    for year in YEARS:
        build(year)


if __name__ == "__main__":
    main()
