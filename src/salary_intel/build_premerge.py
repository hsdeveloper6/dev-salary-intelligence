def build_canonical(root=ROOT, years=YEARS):
    """Step 1: run the cleaning notebooks in a temp folder; copy canonical_{year}.csv to data/clean/."""
    (root / "data/clean").mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        (work / "data").symlink_to(root / "data")      # notebooks read data/<year>/results.csv
        for year in years:
            nb_path = root / f"notebooks/cleaning/clean_{year}_canonical.ipynb"
            print(f"running {nb_path.relative_to(root)} ...")
            nb = nbformat.read(nb_path, as_version=4)
            NotebookClient(nb, timeout=1200, kernel_name="python3",
                           resources={"metadata": {"path": str(work)}}).execute()
            shutil.copyfile(work / f"canonical_{year}.csv",
                            root / f"data/clean/canonical_{year}.csv")


def select_and_rename(canonical, year):
    """Step 2: keep COLUMNS[year] in order, renamed. Fails loudly if a source column is missing."""
    pairs = COLUMNS[year]
    missing = [src for src, _ in pairs if src not in canonical.columns]
    if missing:
        raise KeyError(f"[{year}] canonical file is missing columns: {missing}")
    return canonical[[src for src, _ in pairs]].set_axis([dst for _, dst in pairs], axis=1)


def build_final(year, root=ROOT):
    canonical = pd.read_csv(root / f"data/clean/canonical_{year}.csv", low_memory=False,
                            keep_default_na=False, na_values=[""])
    final = select_and_rename(canonical, year)
    out = root / f"data/premerge_cleaned_dataset/final_canonical_{year}.csv"
    final.to_csv(out, index=False)
    print(f"saved {out.relative_to(root)}: {final.shape[0]:,} rows, {final.shape[1]} columns")


def main():
    build_canonical()
    (ROOT / "data/premerge_cleaned_dataset").mkdir(parents=True, exist_ok=True)
    for year in YEARS:
        build_final(year)


if __name__ == "__main__":
    main()
